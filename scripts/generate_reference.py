"""Regenerates docs/reference/events.md and docs/reference/attributes.md from the code.

Run after adding an event kind or a reserved attribute:

    uv run python scripts/generate_reference.py

``scripts/check_consistency.py`` fails CI when the files are out of date.
"""

from __future__ import annotations

import sys
from pathlib import Path

from fanferro import _core

ROOT = Path(__file__).resolve().parents[1]
EVENTS = ROOT / "docs" / "reference" / "events.md"
ATTRIBUTES = ROOT / "docs" / "reference" / "attributes.md"

ATTRIBUTE_DESCRIPTIONS = {
    "content-type": (
        "Media type of the wire body: `application/cloudevents+json`, `application/cloudevents+protobuf`, "
        "or the payload type for the raw envelope (not written for JSON, which is implied). Used to detect "
        "the envelope.",
        "envelopes (configurable)",
    ),
    "fanferro.type": (
        "Message type name, promoted so SNS filter policies and routers can use it without parsing the body.",
        "envelopes (configurable)",
    ),
    "fanferro.id": (
        "Message id for the raw envelope (other envelopes carry it in the body); stable across retries.",
        "raw envelope",
    ),
    "fanferro.encoding": ("`base64` when the transport base64-encoded a binary body.", "transport"),
    "fanferro.claim-check": ("Marks a claim-check pointer body (`v1`); the payload is stored externally.", "transport"),
    "fanferro.attempt": ("Attempt counter carried across re-enqueues (`RetryPolicy(strategy='requeue')`).", "consumer"),
    "fanferro.dead-letter": (
        "JSON describing why fanferro dead-lettered the message (reason, source, receive count, error, time).",
        "consumer",
    ),
    "ExtendedPayloadSize": (
        "AWS Extended Client Library pointer marker (read always, written with `format='aws_extended'`).",
        "transport",
    ),
    "SQSLargePayloadSize": ("Legacy AWS Extended Client Library pointer marker (read only).", "transport"),
    "traceparent": ("W3C trace context (message-attribute propagation).", "telemetry"),
    "tracestate": ("W3C trace state (message-attribute propagation, when non-empty).", "telemetry"),
    "baggage": ("W3C baggage (only when added to `Propagation.attribute_keys`).", "telemetry"),
}


def render_events() -> str:
    lines = [
        "# Event reference",
        "",
        "<!-- Generated by scripts/generate_reference.py from the Rust EventKind enum. Do not edit. -->",
        "",
        "Every event kind with its default log level. Kinds can be selected with glob patterns",
        '(`"message.*"`) in `client.on(...)` and `LoggingConfig(levels=..., disabled=...)`. Also',
        "available as `fanferro events`.",
        "",
        "| Kind | Default level | Description |",
        "| --- | --- | --- |",
    ]
    lines.extend(f"| `{name}` | {level} | {description} |" for name, level, description in _core.event_kinds())
    return "\n".join(lines) + "\n"


def render_attributes() -> str:
    lines = [
        "# Message attribute reference",
        "",
        "<!-- Generated by scripts/generate_reference.py from crates/fanferro-core/src/types/reserved.rs."
        " Do not edit. -->",
        "",
        "SQS and SNS allow at most **10 message attributes** per message. These are the attributes",
        "fanferro reads or writes; everything else is yours. Names starting with `fanferro.` are reserved",
        "and hidden from `message.attributes` (they remain in `message.raw_attributes`).",
        "",
        "| Attribute | Written by | Meaning |",
        "| --- | --- | --- |",
    ]
    for name in _core.reserved_attributes():
        description, writer = ATTRIBUTE_DESCRIPTIONS[name]
        lines.append(f"| `{name}` | {writer} | {description} |")
    lines += [
        "",
        "Typical budget: a raw message (the default envelope) uses 1-2 attributes (`fanferro.id`, plus",
        "`fanferro.type` for typed messages and `content-type` for non-JSON payloads); a CloudEvents message",
        "uses 2 (`content-type`, `fanferro.type`). Trace context with message-attribute propagation adds 1-2,",
        "leaving 6-7 for application attributes. Disable what you do not need",
        "(`Raw(type_attribute=None)`, `CloudEvents(content_type_attribute=False, type_attribute=None)`,",
        "`Propagation(inject=(Carrier.AWS_TRACE_HEADER,))`).",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    missing = set(_core.reserved_attributes()) - set(ATTRIBUTE_DESCRIPTIONS)
    if missing:
        print(f"describe these attributes in scripts/generate_reference.py: {sorted(missing)}", file=sys.stderr)
        return 1
    EVENTS.write_text(render_events())
    ATTRIBUTES.write_text(render_attributes())
    print(f"wrote {EVENTS.relative_to(ROOT)} and {ATTRIBUTES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
